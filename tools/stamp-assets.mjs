// Stamps the blog's scripts and the stylesheets with a hash of their contents (?v=…), so that after a change every
// browser loads the new files together. GitHub Pages lets browsers keep a file for 10 minutes; without this a
// browser can mix a new editor.js with a backend.js it kept, and an import that isn't there yet stops the page.
// Modules are stamped through an import map, which the browser applies to every import, nested ones included.
// Run it after changing anything in js/blog or css: node tools/stamp-assets.mjs (the Blog pages workflow runs it too).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const MARK = "<!-- generated by tools/build-blog.mjs -->"; // as tools/build-blog.mjs writes it
const v = (rel) => crypto.createHash("sha256").update(fs.readFileSync(path.join(ROOT, rel))).digest("hex").slice(0, 10);

const mods = fs.readdirSync(path.join(ROOT, "js/blog")).filter((f) => f.endsWith(".js")).sort().map((f) => "/js/blog/" + f);
const ver = Object.fromEntries([...mods, "/css/style.css", "/css/blog.css"].map((u) => [u, v(u.slice(1))]));
const map = `<script type="importmap">${JSON.stringify({ imports: Object.fromEntries(mods.map((u) => [u, `${u}?v=${ver[u]}`])) })}</script>`;

const pages = ["index.html", "404.html", "blog/index.html", "blog/editor/index.html", "blog/dashboard/index.html", "privacy/index.html"];
for (const d of fs.readdirSync(path.join(ROOT, "blog"), { withFileTypes: true })) {
  const f = path.join("blog", d.name, "index.html");
  if (d.isDirectory() && fs.existsSync(path.join(ROOT, f)) && fs.readFileSync(path.join(ROOT, f), "utf8").includes(MARK)) pages.push(f);
}
for (const rel of pages) {
  const file = path.join(ROOT, rel), was = fs.readFileSync(file, "utf8");
  let s = was.replace(/[ \t]*<script type="importmap">.*?<\/script>\n/g, "")
    .replace(/(href|src)="(\/(?:css|js\/blog)\/[\w-]+\.(?:css|js))(?:\?v=\w+)?"/g, (m, a, u) => (ver[u] ? `${a}="${u}?v=${ver[u]}"` : m));
  if (s.includes('<script type="module"')) s = s.replace(/([ \t]*)<script type="module"/, (m, ind) => `${ind}${map}\n${m}`);
  if (s !== was) { fs.writeFileSync(file, s); console.log("stamped", rel); }
}
